// scuffed-perms Worker: the only thing that can change the Scuffed role lists from the site.
// It also saves the spawn announcements (/announcements) and the world images (/images, see further down).
//
// The editor page (kanaris-beans.com/scuffed_perms/) signs in with the same Supabase player account as the
// games and chat. Every request carries that session (Authorization: Bearer <access token>) and, for the
// master login, the moderation session token (X-Mod-Token). Before anything else the Worker asks Supabase
// who that is (public.mod_me, the same check the moderation panel uses) and refuses anyone below ADMIN.
// Hiding the editor in the page is only convenience: this check is what keeps everyone else out.
//
// GET  /lists  -> { head, files: [{ name, sha, text }] }       (admins only)
// POST /save   <- { head, changes: { "<file>": { sha, names: [..] } } }
//              -> { commit, files }   one commit: the changed lists + a rebuilt all.txt
//
// Config: cloudflare.config.ts (Supabase URL + anon key are public). GITHUB_TOKEN is a secret added after
// deploying (npx wrangler secret put GITHUB_TOKEN --name scuffed-perms). Without it the lists can still be
// viewed (read from the public all.txt) but /save refuses.
//
// A list's "sha" here is a hash of its non-blank lines, not GitHub's blob id, so it means the same thing
// whether the lists came from the GitHub API or from all.txt.

const ADMIN_LEVEL = 3;      // role lists: admin and up
const MODERATOR_LEVEL = 2;  // announcements: moderator and up
// (helper 1, moderator 2, admin 3, dev 4, master 5 - supabase/migrations/2026-10-10-chat-moderation.sql)
const BUNDLE = "all.txt";
const MAX_NAMES = 500;
const MAX_NAME_LENGTH = 64;

// ---------- small helpers ----------

function corsHeaders(request, env) {
  const origin = request.headers.get("Origin") || "";
  const allowed = String(env.ALLOWED_ORIGINS || "").split(",").map((s) => s.trim()).filter(Boolean);
  const headers = {
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Authorization, Content-Type, X-Mod-Token",
    "Access-Control-Max-Age": "86400",
    Vary: "Origin",
  };
  if (allowed.includes(origin)) headers["Access-Control-Allow-Origin"] = origin;
  return headers;
}

function json(data, status, cors) {
  return new Response(JSON.stringify(data), {
    status: status || 200,
    headers: { "Content-Type": "application/json", "Cache-Control": "no-store", ...cors },
  });
}

class HttpError extends Error {
  constructor(status, message) { super(message); this.status = status; }
}

function encodeBase64(str) {
  const bytes = new TextEncoder().encode(str);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

function decodeBase64(b64) {
  const bin = atob(String(b64).replace(/\s/g, ""));
  return new TextDecoder().decode(Uint8Array.from(bin, (c) => c.charCodeAt(0)));
}

function splitLines(text) {
  return String(text || "").replace(/\r/g, "").split("\n").filter((l) => !/^\s*$/.test(l));
}

const byteOrder = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Identifies a list's contents (blank lines and CRs ignored), for "did someone else change it?".
async function contentId(text) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(splitLines(text).join("\n")));
  return "h" + [...new Uint8Array(digest)].slice(0, 12).map((b) => b.toString(16).padStart(2, "0")).join("");
}

// The lists from the public all.txt: { name, text } per "### FILE:" section.
function parseBundle(text) {
  const files = [];
  let current = null;
  for (const line of String(text || "").replace(/\r/g, "").split("\n")) {
    if (line.startsWith("### FILE: ")) { current = { name: line.slice(10).trim(), lines: [] }; files.push(current); continue; }
    if (current && !/^\s*$/.test(line)) current.lines.push(line);
  }
  return files.map((f) => ({ name: f.name, text: f.lines.length ? f.lines.join("\n") + "\n" : "" }));
}

// Same output as .github/scripts/combine-scuffed-perms.sh (and the old page). Keep them in step.
function buildBundle(dir, fileLines) {
  const out = [
    "# AUTO-GENERATED - do not edit this file.",
    `# Built from the other files in ${dir}/ (kanaris-beans.com/scuffed_perms/ or .github/workflows/combine-scuffed-perms.yml).`,
    "# Edit the individual role files instead.",
  ];
  for (const name of Object.keys(fileLines).sort(byteOrder)) {
    out.push("", `### FILE: ${name}`, ...fileLines[name]);
  }
  return out.join("\n") + "\n";
}

// Why a name can't go on a list, or "" if it can. Mirrors the checks in the page.
function nameProblem(name) {
  if (!name) return "empty name";
  if (name.length > MAX_NAME_LENGTH) return `"${name.slice(0, 20)}…" is longer than ${MAX_NAME_LENGTH} characters`;
  if (/[\r\n]/.test(name)) return "names can't contain line breaks";
  if (name.includes(",")) return `"${name}" contains a comma (the world reads a comma as "next name")`;
  if (name.startsWith("#") || name.startsWith("//")) return `"${name}" starts with # or // (the world reads that as a comment)`;
  if (name.startsWith("### FILE:")) return `"${name}" is reserved`;
  return "";
}

// ---------- Supabase: who is asking? ----------

async function staffOf(request, env, need = ADMIN_LEVEL) {
  const auth = request.headers.get("Authorization") || "";
  const userJwt = auth.startsWith("Bearer ") ? auth.slice(7).trim() : "";
  const modToken = (request.headers.get("X-Mod-Token") || "").trim();
  if (!userJwt && !modToken) throw new HttpError(401, "Sign in first.");

  const res = await fetch(`${env.SUPABASE_URL}/rest/v1/rpc/mod_me`, {
    method: "POST",
    headers: {
      apikey: env.SUPABASE_ANON_KEY,
      Authorization: `Bearer ${userJwt || env.SUPABASE_ANON_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ token: modToken || null }),
  });
  if (res.status === 401) throw new HttpError(401, "Your sign-in has expired. Reload the page.");
  if (!res.ok) throw new HttpError(502, `Couldn't check your staff level (${res.status}).`);
  const me = await res.json();
  const level = Number(me && me.level) || 0;
  if (level < need) throw new HttpError(403, need >= ADMIN_LEVEL ? "Admins only." : "Moderators only.");
  return { level, actor: (me && me.actor) || "admin" };
}

// ---------- GitHub ----------

class GitHub {
  constructor(env) {
    this.base = `https://api.github.com/repos/${env.REPO_OWNER}/${env.REPO_NAME}`;
    this.branch = env.BRANCH || "main";
    this.dir = env.ROLES_DIR || "scuffed_perms/roles";
    this.raw = `https://raw.githubusercontent.com/${env.REPO_OWNER}/${env.REPO_NAME}/refs/heads/${this.branch}/`;
    this.headers = {
      Accept: "application/vnd.github+json",
      "User-Agent": "scuffed-perms",
      "X-GitHub-Api-Version": "2022-11-28",
    };
    if (env.GITHUB_TOKEN) this.headers.Authorization = `Bearer ${env.GITHUB_TOKEN}`;
  }

  // No token: read the lists from the public all.txt (can lag a few minutes behind a save: GitHub's CDN).
  async listsFromBundle() {
    const res = await fetch(this.raw + this.dir + "/" + BUNDLE, { headers: { "User-Agent": "scuffed-perms" } });
    if (!res.ok) throw new HttpError(502, `Couldn't read ${BUNDLE} (${res.status}).`);
    const files = parseBundle(await res.text());
    return Promise.all(files.map(async (f) => ({ ...f, sha: await contentId(f.text) })));
  }

  async call(path, method, body) {
    const res = await fetch(this.base + path, {
      method: method || "GET",
      headers: body ? { ...this.headers, "Content-Type": "application/json" } : this.headers,
      body: body ? JSON.stringify(body) : undefined,
    });
    const text = await res.text();
    let data = null;
    try { data = text ? JSON.parse(text) : null; } catch { data = text; }
    if (!res.ok) {
      const err = new HttpError(res.status === 409 || res.status === 422 ? 409 : 502,
        `GitHub ${method || "GET"} ${path} failed: ${res.status} ${(data && data.message) || ""}`.trim());
      err.github = res.status;
      throw err;
    }
    return data;
  }

  head() { return this.call(`/git/ref/heads/${this.branch}`).then((d) => d.object.sha); }

  // Every role list at a commit, all.txt left out.
  async lists(commit) {
    const items = await this.call(`/contents/${this.dir.split("/").map(encodeURIComponent).join("/")}?ref=${commit}`);
    const files = (items || []).filter((it) => it.type === "file" && it.name !== BUNDLE);
    return Promise.all(files.map(async (f) => {
      const blob = await this.call(`/git/blobs/${f.sha}`);
      const text = decodeBase64(blob.content);
      return { name: f.name, sha: await contentId(text), text };
    }));
  }

  // One file's text at a commit, or null if it doesn't exist.
  async file(path, commit) {
    const res = await fetch(`${this.base}/contents/${path.split("/").map(encodeURIComponent).join("/")}?ref=${commit}`, { headers: this.headers });
    if (res.status === 404) return null;
    if (!res.ok) throw new HttpError(502, `GitHub GET ${path} failed: ${res.status}`);
    const data = await res.json();
    return decodeBase64(data.content);
  }

  async commit(head, tree, message) {
    const parent = await this.call(`/git/commits/${head}`);
    const newTree = await this.call("/git/trees", "POST", { base_tree: parent.tree.sha, tree });
    const commit = await this.call("/git/commits", "POST", { message, tree: newTree.sha, parents: [head] });
    await this.call(`/git/refs/heads/${this.branch}`, "PATCH", { sha: commit.sha, force: false });
    return commit.sha;
  }
}

// ---------- handlers ----------

async function handleLists(env) {
  const gh = new GitHub(env);
  if (!env.GITHUB_TOKEN) return { head: null, files: await gh.listsFromBundle(), canSave: false };
  const head = await gh.head();
  const files = await gh.lists(head);
  return { head, files, canSave: true };
}

async function handleSave(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  let body;
  try { body = await request.json(); } catch { throw new HttpError(400, "Body must be JSON."); }
  const changes = body && body.changes && typeof body.changes === "object" ? body.changes : null;
  if (!changes || !Object.keys(changes).length) throw new HttpError(400, "Nothing to save.");

  const gh = new GitHub(env);

  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const current = await gh.lists(head);
    const byName = Object.fromEntries(current.map((f) => [f.name, f]));

    // Only existing role files can be edited, and only from the version the editor loaded.
    const clashes = [];
    const fileLines = Object.fromEntries(current.map((f) => [f.name, splitLines(f.text)]));
    const tree = [];
    const summary = [];
    for (const [name, change] of Object.entries(changes)) {
      const file = byName[name];
      if (!file) throw new HttpError(400, `There's no role list called "${name}".`);
      if (!change || !Array.isArray(change.names)) throw new HttpError(400, `Bad change for "${name}".`);
      if (change.sha !== file.sha) { clashes.push(name); continue; }
      if (change.names.length > MAX_NAMES) throw new HttpError(400, `"${name}" can hold at most ${MAX_NAMES} names.`);

      // Comment lines in the file stay where they are; the names become exactly what the editor sent.
      const names = [];
      const seen = new Set();
      for (const raw of change.names) {
        const n = String(raw).trim();
        const problem = nameProblem(n);
        if (problem) throw new HttpError(400, `${name}: ${problem}.`);
        if (seen.has(n.toLowerCase())) continue;
        seen.add(n.toLowerCase());
        names.push(n);
      }
      const before = fileLines[name];
      const isComment = (l) => { const t = l.trim(); return t.startsWith("#") || t.startsWith("//"); };
      const lines = [...before.filter(isComment), ...names];
      const oldNames = before.filter((l) => !isComment(l)).map((l) => l.trim());
      const added = names.filter((n) => !oldNames.some((o) => o.toLowerCase() === n.toLowerCase()));
      const removed = oldNames.filter((o) => !names.some((n) => n.toLowerCase() === o.toLowerCase()));
      if (!added.length && !removed.length && lines.join("\n") === before.join("\n")) continue;
      fileLines[name] = lines;
      tree.push({ path: `${gh.dir}/${name}`, mode: "100644", type: "blob", content: lines.length ? lines.join("\n") + "\n" : "" });
      summary.push(`${name} ${[...added.map((n) => "+" + n), ...removed.map((n) => "-" + n)].join(" ")}`.trim());
    }
    if (clashes.length) {
      throw new HttpError(409, `Someone else changed ${clashes.join(", ")} after you opened the page. Reload and make your changes again.`);
    }
    if (!tree.length) return { commit: null, unchanged: true };

    tree.push({ path: `${gh.dir}/${BUNDLE}`, mode: "100644", type: "blob", content: buildBundle(gh.dir, fileLines) });
    let message = `Scuffed perms: ${summary.join("; ")}`;
    if (message.length > 300) message = message.slice(0, 297) + "...";
    message += `\n\nSaved by ${who.actor} from kanaris-beans.com/scuffed_perms/`;

    try {
      const commit = await gh.commit(head, tree, message);
      return { commit };
    } catch (err) {
      // The branch moved between our read and our write: start again from the new head once.
      if (err.github === 422 && attempt < 1) continue;
      throw err;
    }
  }
}

// ---------- spawn announcements (each world's board reads <world>/announcements.txt) ----------

const WORLDS = { scuffed: "Scuffed", straya: "Straya" };
const MAX_ANNOUNCEMENT = 8000;

// Identifies an announcement's exact text (only CRs ignored: blank lines matter on the board).
async function textId(text) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(String(text || "").replace(/\r/g, "")));
  return "t" + [...new Uint8Array(digest)].slice(0, 12).map((b) => b.toString(16).padStart(2, "0")).join("");
}

function worldOf(value) {
  const w = String(value || "").toLowerCase();
  if (!Object.hasOwn(WORLDS, w)) throw new HttpError(400, "Pick a world: scuffed or straya.");
  return w;
}

async function handleAnnouncementGet(request, env) {
  const world = worldOf(new URL(request.url).searchParams.get("world"));
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "The perms server still needs its GitHub token.");
  const gh = new GitHub(env);
  const text = await gh.file(`${world}/announcements.txt`, await gh.head());
  return { world, exists: text !== null, text: text || "", sha: await textId(text || ""), canSave: true };
}

async function handleAnnouncementSave(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  let body;
  try { body = await request.json(); } catch { throw new HttpError(400, "Body must be JSON."); }
  const world = worldOf(body && body.world);
  const text = String((body && body.text) || "").replace(/\r/g, "");
  if (text.length > MAX_ANNOUNCEMENT) throw new HttpError(400, `Announcements can be at most ${MAX_ANNOUNCEMENT} characters.`);
  const gh = new GitHub(env);
  const path = `${world}/announcements.txt`;
  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const current = await gh.file(path, head);
    if ((body.sha || "") !== await textId(current || "")) {
      throw new HttpError(409, `Someone else changed the ${WORLDS[world]} announcements after you opened them. Reload and make your changes again.`);
    }
    if (current !== null && current.replace(/\r/g, "") === text) return { commit: null, unchanged: true };
    const content = text.endsWith("\n") || !text ? text : text + "\n";
    try {
      const commit = await gh.commit(head, [{ path, mode: "100644", type: "blob", content }],
        `${WORLDS[world]} announcements update\n\nSaved by ${who.actor} from kanaris-beans.com/scuffed_perms/`);
      return { commit, sha: await textId(content) };
    } catch (err) {
      if (err.github === 422 && attempt < 1) continue;
      throw err;
    }
  }
}

// ---------- world images (kanaris-beans.com/scuffed_dev/images/) ----------
//
// GET  /images        -> { head, canSave, files: [{ path, sha, size }], manifest }   (moderators and up)
// GET  /images/log    -> { commits: [{ sha, date, message }] }   the folder's history: the page's audit console
// POST /images        <- { ops: [ { op: "put", path, data, sha|null, from, w, h }      new (sha null) or replace
//                               { op: "delete", path, sha }
//                               { op: "move", path, to, sha } ] }
//                     -> { commit, changes: [{ path, sha|null }] }   one commit for the whole batch
//
// Paths are "<folder>/<name>.png" under IMAGES_DIR. The page converts every upload to a PNG whose longest side is
// at most 512px before sending it; this checks the PNG header again, so nothing else gets in. Every op carries the
// sha the page last saw, so two people replacing the same image can't overwrite each other silently.
// manifest.json in the folder keeps who uploaded what, from which file, and when (shown on the page).

const IMAGES_DIR = "scuffed/images";
const IMAGE_LEVEL = MODERATOR_LEVEL;
const IMAGE_MANIFEST = "manifest.json";
const IMAGE_MAX_SIDE = 512;
const IMAGE_MAX_BYTES = 3 * 1024 * 1024;
const IMAGE_MAX_OPS = 24;
const IMAGE_MAX_BODY = 10 * 1024 * 1024;
const FOLDER_RE = /^[a-z0-9][a-z0-9_-]{0,47}$/;
const FILE_RE = /^[a-z0-9][a-z0-9_-]{0,63}\.png$/;

function imagePath(value) {
  const p = String(value || "");
  const parts = p.split("/");
  if (parts.length !== 2 || !FOLDER_RE.test(parts[0]) || !FILE_RE.test(parts[1])) {
    throw new HttpError(400, `"${p.slice(0, 80)}" isn't a valid image path (folder/name.png, lowercase letters, numbers, - and _).`);
  }
  return p;
}

// Width and height from a base64 PNG, or an error if it isn't one. Only the first 24 bytes are decoded.
function pngSize(b64) {
  const head = atob(String(b64).slice(0, 32));
  const sig = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  for (let i = 0; i < 8; i++) if (head.charCodeAt(i) !== sig[i]) throw new HttpError(400, "Uploads must be PNG files.");
  if (head.slice(12, 16) !== "IHDR") throw new HttpError(400, "That PNG has no header.");
  const u32 = (o) => ((head.charCodeAt(o) << 24) >>> 0) + (head.charCodeAt(o + 1) << 16) + (head.charCodeAt(o + 2) << 8) + head.charCodeAt(o + 3);
  return { w: u32(16), h: u32(20) };
}

async function imageFiles(gh, commit) {
  const root = await gh.call(`/contents/${IMAGES_DIR.split("/").slice(0, -1).join("/")}?ref=${commit}`);
  const dir = (root || []).find((it) => it.type === "dir" && it.name === IMAGES_DIR.split("/").pop());
  if (!dir) return [];
  const tree = await gh.call(`/git/trees/${dir.sha}?recursive=1`);
  return (tree.tree || []).filter((t) => t.type === "blob").map((t) => ({ path: t.path, sha: t.sha, size: t.size || 0 }));
}

async function readManifest(gh, commit) {
  const text = await gh.file(`${IMAGES_DIR}/${IMAGE_MANIFEST}`, commit);
  if (!text) return { files: {} };
  try {
    const m = JSON.parse(text);
    if (!m.files || typeof m.files !== "object") m.files = {};
    return m;
  } catch { return { files: {} }; }
}

async function handleImagesGet(env) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "The perms server still needs its GitHub token.");
  const gh = new GitHub(env);
  const head = await gh.head();
  const [files, manifest] = await Promise.all([imageFiles(gh, head), readManifest(gh, head)]);
  return { head, canSave: true, files: files.filter((f) => f.path !== IMAGE_MANIFEST), manifest: manifest.files };
}

async function handleImagesLog(env) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "The perms server still needs its GitHub token.");
  const gh = new GitHub(env);
  const list = await gh.call(`/commits?sha=${gh.branch}&path=${IMAGES_DIR}&per_page=40`);
  return { commits: (list || []).map((c) => ({ sha: c.sha, date: c.commit.author.date, message: c.commit.message })) };
}

async function handleImagesSave(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  const raw = await request.text();
  if (raw.length > IMAGE_MAX_BODY) throw new HttpError(413, "That batch is too big. Send fewer images at once.");
  let body;
  try { body = JSON.parse(raw); } catch { throw new HttpError(400, "Body must be JSON."); }
  const ops = body && Array.isArray(body.ops) ? body.ops : null;
  if (!ops || !ops.length) throw new HttpError(400, "Nothing to save.");
  if (ops.length > IMAGE_MAX_OPS) throw new HttpError(400, `At most ${IMAGE_MAX_OPS} changes at once.`);

  // Check every op before touching GitHub.
  const touched = new Set();
  const clean = ops.map((o) => {
    const op = String(o && o.op);
    const path = imagePath(o.path);
    const c = { op, path, sha: o.sha ? String(o.sha) : null };
    if (op === "put") {
      const data = String(o.data || "");
      if (!data || !/^[A-Za-z0-9+/]+=*$/.test(data)) throw new HttpError(400, `${path}: missing or broken image data.`);
      if (data.length * 0.75 > IMAGE_MAX_BYTES) throw new HttpError(400, `${path} is bigger than ${IMAGE_MAX_BYTES / 1048576} MB.`);
      const size = pngSize(data);
      if (!size.w || !size.h || size.w > IMAGE_MAX_SIDE || size.h > IMAGE_MAX_SIDE) {
        throw new HttpError(400, `${path} is ${size.w}x${size.h}. Images can be at most ${IMAGE_MAX_SIDE}px on their longest side.`);
      }
      Object.assign(c, { data, w: size.w, h: size.h, from: String(o.from || "").slice(0, 120) });
    } else if (op === "move") {
      c.to = imagePath(o.to);
      if (!c.sha) throw new HttpError(400, `${path}: rename needs the image's sha.`);
      if (touched.has(c.to)) throw new HttpError(400, `${c.to} appears twice in one save.`);
      touched.add(c.to);
    } else if (op === "delete") {
      if (!c.sha) throw new HttpError(400, `${path}: delete needs the image's sha.`);
    } else {
      throw new HttpError(400, `Unknown change "${op}".`);
    }
    if (touched.has(path)) throw new HttpError(400, `${path} appears twice in one save.`);
    touched.add(path);
    return c;
  });

  const gh = new GitHub(env);
  // Blobs don't depend on the branch, so they're made once even if the commit has to be retried.
  const blobs = {};
  for (const c of clean) {
    if (c.op === "put") blobs[c.path] = (await gh.call("/git/blobs", "POST", { content: c.data, encoding: "base64" })).sha;
  }

  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const [files, manifest] = await Promise.all([imageFiles(gh, head), readManifest(gh, head)]);
    const current = Object.fromEntries(files.map((f) => [f.path, f.sha]));
    const clashes = [];
    for (const c of clean) {
      const now = current[c.path] || null;
      if (c.op === "put" && c.sha !== now) clashes.push(now ? `${c.path} (it already exists or changed)` : `${c.path} (it was deleted)`);
      if ((c.op === "delete" || c.op === "move") && c.sha !== now) clashes.push(c.path);
      if (c.op === "move" && current[c.to]) clashes.push(`${c.to} (already taken)`);
    }
    if (clashes.length) throw new HttpError(409, `Someone else changed ${clashes.join(", ")} after you loaded the page. It has been refreshed; try again.`);

    const at = new Date().toISOString();
    const tree = [];
    const lines = [];
    const changes = [];
    const counts = { put: 0, rep: 0, del: 0, mov: 0 };
    for (const c of clean) {
      const full = `${IMAGES_DIR}/${c.path}`;
      if (c.op === "put") {
        tree.push({ path: full, mode: "100644", type: "blob", sha: blobs[c.path] });
        manifest.files[c.path] = { w: c.w, h: c.h, from: c.from || undefined, by: who.actor, at };
        changes.push({ path: c.path, sha: blobs[c.path] });
        if (c.sha) { counts.rep++; lines.push(`~ ${c.path}${c.from ? `  (from ${c.from})` : ""}`); }
        else { counts.put++; lines.push(`+ ${c.path}${c.from ? `  (from ${c.from})` : ""}`); }
      } else if (c.op === "delete") {
        tree.push({ path: full, mode: "100644", type: "blob", sha: null });
        delete manifest.files[c.path];
        changes.push({ path: c.path, sha: null });
        counts.del++; lines.push(`- ${c.path}`);
      } else {
        tree.push({ path: `${IMAGES_DIR}/${c.to}`, mode: "100644", type: "blob", sha: c.sha });
        tree.push({ path: full, mode: "100644", type: "blob", sha: null });
        manifest.files[c.to] = Object.assign({}, manifest.files[c.path] || {}, { by: who.actor, at });
        delete manifest.files[c.path];
        changes.push({ path: c.path, sha: null }, { path: c.to, sha: c.sha });
        counts.mov++; lines.push(`> ${c.path} -> ${c.to}`);
      }
    }
    const sorted = Object.fromEntries(Object.keys(manifest.files).sort(byteOrder).map((k) => [k, manifest.files[k]]));
    tree.push({ path: `${IMAGES_DIR}/${IMAGE_MANIFEST}`, mode: "100644", type: "blob", content: JSON.stringify({ ...manifest, files: sorted }, null, 1) + "\n" });

    const words = [];
    if (counts.put) words.push(`add ${counts.put}`);
    if (counts.rep) words.push(`replace ${counts.rep}`);
    if (counts.mov) words.push(`rename ${counts.mov}`);
    if (counts.del) words.push(`delete ${counts.del}`);
    const message = `Scuffed images: ${words.join(", ")}\n\n${lines.join("\n")}\n\nSaved by ${who.actor} from kanaris-beans.com/scuffed_dev/images/`;
    try {
      const commit = await gh.commit(head, tree, message);
      return { commit, changes };
    } catch (err) {
      if (err.github === 422 && attempt < 1) continue;
      throw err;
    }
  }
}

export default {
  async fetch(request, env) {
    const cors = corsHeaders(request, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    const { pathname } = new URL(request.url);

    try {
      if (request.method === "GET" && pathname === "/health") return json({ ok: true }, 200, cors);

      if (request.method === "GET" && pathname === "/lists") {
        const who = await staffOf(request, env);
        return json({ ...(await handleLists(env)), you: who }, 200, cors);
      }
      if (request.method === "POST" && pathname === "/save") {
        const who = await staffOf(request, env);
        return json(await handleSave(request, env, who), 200, cors);
      }
      if (request.method === "GET" && pathname === "/announcements") {
        await staffOf(request, env, MODERATOR_LEVEL);
        return json(await handleAnnouncementGet(request, env), 200, cors);
      }
      if (request.method === "POST" && pathname === "/announcements") {
        const who = await staffOf(request, env, MODERATOR_LEVEL);
        return json(await handleAnnouncementSave(request, env, who), 200, cors);
      }
      if (request.method === "GET" && pathname === "/images") {
        const who = await staffOf(request, env, IMAGE_LEVEL);
        return json({ ...(await handleImagesGet(env)), you: who }, 200, cors);
      }
      if (request.method === "GET" && pathname === "/images/log") {
        await staffOf(request, env, IMAGE_LEVEL);
        return json(await handleImagesLog(env), 200, cors);
      }
      if (request.method === "POST" && pathname === "/images") {
        const who = await staffOf(request, env, IMAGE_LEVEL);
        return json(await handleImagesSave(request, env, who), 200, cors);
      }
      return json({ error: "Not found" }, 404, cors);
    } catch (err) {
      const status = err instanceof HttpError ? err.status : 500;
      if (status >= 500) console.error(`${request.method} ${pathname}:`, err);
      return json({ error: err.message || "Something went wrong" }, status, cors);
    }
  },
};
