async function handleImagesSuggest(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  const raw = await request.text();
  if (raw.length > IMAGE_MAX_BODY) throw new HttpError(413, "That batch is too big. Send fewer images at once.");
  let body;
  try { body = JSON.parse(raw); } catch { throw new HttpError(400, "Body must be JSON."); }
  const items = body && Array.isArray(body.items) ? body.items : null;
  if (!items || !items.length) throw new HttpError(400, "Nothing to suggest.");
  if (items.length > IMAGE_MAX_OPS) throw new HttpError(400, `At most ${IMAGE_MAX_OPS} suggestions at once.`);
  const note = String((body && body.note) || "").replace(/\r/g, "").trim().slice(0, MAX_NOTE);
  const seen = new Set();
  const clean = items.map((o) => {
    const path = imagePath(o && o.path);
    if (seen.has(path)) throw new HttpError(400, `${path} appears twice in one suggestion.`);
    seen.add(path);
    return { path, sha: o.sha ? String(o.sha) : null, from: String(o.from || "").slice(0, 120), ...checkPng(path, o.data) };
  });

  const gh = new GitHub(env);
  const head = await gh.head();
  const files = await imageFiles(gh, head);
  const current = Object.fromEntries(files.map((f) => [f.path, f.sha]));
  const stale = clean.filter((c) => (current[c.path] || null) !== c.sha).map((c) => c.path);
  if (stale.length) throw new HttpError(409, `${stale.join(", ")} changed after you loaded the page. It has been refreshed; try again.`);

  for (const c of clean) c.blob = (await gh.call("/git/blobs", "POST", { content: c.data, encoding: "base64" })).sha;

  for (let attempt = 0; ; attempt++) {
    const sugg = await readSuggestions(gh);
    if (sugg.list.length + clean.length > MAX_SUGGESTIONS) throw new HttpError(400, `There are already ${sugg.list.length} suggestions waiting. Ask a developer to review some first.`);
    const at = new Date().toISOString();
    const added = clean.map((c, i) => {
      const id = Date.now().toString(36) + i + Math.random().toString(36).slice(2, 7);
      return { id, path: c.path, sha: c.sha, file: `pending/${id}.png`, blob: c.blob, w: c.w, h: c.h, from: c.from || undefined, note: note || undefined, by: who.actor, at };
    });
    const tree = suggestionsTree([...sugg.list, ...added], added.map((s) => ({ path: s.file, mode: "100644", type: "blob", sha: s.blob })));
    const lines = added.map((s) => `? ${s.path}  (${s.sha ? "replace" : "new"}${s.from ? `, from ${s.from}` : ""})`);
    const message = `Image suggestion: ${added.length === 1 ? added[0].path : added.length + " images"}\n\n${lines.join("\n")}${note ? `\n\nNote: ${note}` : ""}\n\nSuggested by ${who.actor} from kanaris-beans.com/scuffed_dev/images/`;
    try {
      const commit = await gh.commitOn(SUGGEST_BRANCH, sugg.head, tree, message);
      return { commit, suggestions: added };
    } catch (err) {
      if (err.github === 422 && attempt < SAVE_RETRIES) { await backoff(attempt); continue; }
      throw err;
    }
  }
}

async function handleImagesReview(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  let body;
  try { body = await request.json(); } catch { throw new HttpError(400, "Body must be JSON."); }
  const action = String(body && body.action);
  if (!["approve", "reject", "withdraw"].includes(action)) throw new HttpError(400, "Pick approve, reject or withdraw.");
  const reason = String((body && body.reason) || "").replace(/\r/g, "").trim().slice(0, MAX_NOTE);
  const gh = new GitHub(env);
  const sugg = await readSuggestions(gh);
  const s = sugg.list.find((x) => x.id === String(body.id));
  if (!s) throw new HttpError(404, "That suggestion isn't waiting any more: someone already reviewed or withdrew it.");
  if (action === "withdraw" && s.by !== who.actor && who.level < IMAGE_DEV_LEVEL) throw new HttpError(403, "Only the person who suggested it can withdraw it.");
  if (action !== "withdraw" && who.level < IMAGE_DEV_LEVEL) throw new HttpError(403, "Only developers can approve or reject suggestions.");

  let commit = null, live = [];
  if (action === "approve") {
    for (let attempt = 0; ; attempt++) {
      const head = await gh.head();
      const [files, manifest] = await Promise.all([imageFiles(gh, head), readManifest(gh, head)]);
      const now = (files.find((f) => f.path === s.path) || {}).sha || null;
      if (now !== s.sha && !body.force) {
        const e = new HttpError(409, now
          ? `${s.path} has changed since this was suggested. Approve anyway to replace the newer picture.`
          : `${s.path} was ${s.sha ? "deleted" : "added by someone else"} since this was suggested.`);
        e.code = "slot-changed";
        throw e;
      }
      const at = new Date().toISOString();
      manifest.files[s.path] = { w: s.w, h: s.h, from: s.from, by: s.by, approvedBy: who.actor, at, note: s.note };
      const sorted = Object.fromEntries(Object.keys(manifest.files).sort(byteOrder).map((k) => [k, manifest.files[k]]));
      const tree = [
        { path: `${IMAGES_DIR}/${s.path}`, mode: "100644", type: "blob", sha: s.blob },
        { path: `${IMAGES_DIR}/${IMAGE_MANIFEST}`, mode: "100644", type: "blob", content: JSON.stringify({ ...manifest, files: sorted }, null, 1) + "\n" },
      ];
      const message = `Scuffed images: approve ${now ? "replacement" : "new image"}\n\n${now ? "~" : "+"} ${s.path}  (${s.from ? `from ${s.from}, ` : ""}suggested by ${s.by})\n\nApproved by ${who.actor}; suggested by ${s.by} from kanaris-beans.com/scuffed_dev/images/`;
      try { commit = await gh.commit(head, tree, message); live = await liveFiles(tree); break; } catch (err) {
        if (err.github === 422 && attempt < SAVE_RETRIES) { await backoff(attempt); continue; }
        throw err;
      }
    }
  }

  // take it off the waiting list (re-read: someone may have suggested something meanwhile)
  for (let attempt = 0; ; attempt++) {
    const now = attempt ? await readSuggestions(gh) : sugg;
    const list = now.list.filter((x) => x.id !== s.id);
    if (list.length === now.list.length) break;
    const word = { approve: "approved", reject: "rejected", withdraw: "withdrawn" }[action];
    const by = { approve: "Approved", reject: "Rejected", withdraw: "Withdrawn" }[action];
    const message = `Image suggestion ${word}: ${s.path}\n\n${action === "approve" ? "=" : "x"} ${s.path}  (suggested by ${s.by})${reason ? `\n\nReason: ${reason}` : ""}\n\n${by} by ${who.actor} from kanaris-beans.com/scuffed_dev/images/`;
    try {
      await gh.commitOn(SUGGEST_BRANCH, now.head, suggestionsTree(list, [{ path: s.file, mode: "100644", type: "blob", sha: null }]), message);
      break;
    } catch (err) {
      if (err.github === 422 && attempt < SAVE_RETRIES) { await backoff(attempt); continue; }
      throw err;
    }
  }
  return { ok: true, action, commit, live, path: s.path, sha: action === "approve" ? s.blob : null };
}

async function handleImagesSave(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  const raw = await request.text();
  if (raw.length > IMAGE_MAX_BODY) throw new HttpError(413, "That batch is too big. Send fewer images at once.");
  let body;
  try { body = JSON.parse(raw); } catch { throw new HttpError(400, "Body must be JSON."); }
  const ops = body && Array.isArray(body.ops) ? body.ops : null;
  if (!ops || !ops.length) throw new HttpError(400, "Nothing to save.");
  if (ops.length > IMAGE_MAX_OPS) throw new HttpError(400, `At most ${IMAGE_MAX_OPS} changes at once.`);

  // Check every op before touching GitHub.
  const touched = new Set();
  const clean = ops.map((o) => {
    const op = String(o && o.op);
    const path = imagePath(o.path);
    const c = { op, path, sha: o.sha ? String(o.sha) : null };
    if (op === "put") {
      Object.assign(c, checkPng(path, o.data), { from: String(o.from || "").slice(0, 120) });
    } else if (op === "move") {
      c.to = imagePath(o.to);
      if (!c.sha) throw new HttpError(400, `${path}: rename needs the image's sha.`);
      if (touched.has(c.to)) throw new HttpError(400, `${c.to} appears twice in one save.`);
      touched.add(c.to);
    } else if (op === "delete") {
      if (!c.sha) throw new HttpError(400, `${path}: delete needs the image's sha.`);
    } else {
      throw new HttpError(400, `Unknown change "${op}".`);
    }
    if (touched.has(path)) throw new HttpError(400, `${path} appears twice in one save.`);
    touched.add(path);
    return c;
  });

  const gh = new GitHub(env);
  // Blobs don't depend on the branch, so they're made once even if the commit has to be retried.
  const blobs = {};
  for (const c of clean) {
    if (c.op === "put") blobs[c.path] = (await gh.call("/git/blobs", "POST", { content: c.data, encoding: "base64" })).sha;
  }

  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const [files, manifest] = await Promise.all([imageFiles(gh, head), readManifest(gh, head)]);
    const current = Object.fromEntries(files.map((f) => [f.path, f.sha]));
    const clashes = [];
    for (const c of clean) {
      const now = current[c.path] || null;
      if (c.op === "put" && c.sha !== now) clashes.push(now ? `${c.path} (it already exists or changed)` : `${c.path} (it was deleted)`);
      if ((c.op === "delete" || c.op === "move") && c.sha !== now) clashes.push(c.path);
      if (c.op === "move" && current[c.to]) clashes.push(`${c.to} (already taken)`);
    }
    if (clashes.length) throw new HttpError(409, `Someone else changed ${clashes.join(", ")} after you loaded the page. It has been refreshed; try again.`);

    const at = new Date().toISOString();
    const tree = [];
    const lines = [];
    const changes = [];
    const counts = { put: 0, rep: 0, del: 0, mov: 0 };
    for (const c of clean) {
      const full = `${IMAGES_DIR}/${c.path}`;
      if (c.op === "put") {
        tree.push({ path: full, mode: "100644", type: "blob", sha: blobs[c.path] });
        manifest.files[c.path] = { w: c.w, h: c.h, from: c.from || undefined, by: who.actor, at };
        changes.push({ path: c.path, sha: blobs[c.path] });
        if (c.sha) { counts.rep++; lines.push(`~ ${c.path}${c.from ? `  (from ${c.from})` : ""}`); }
        else { counts.put++; lines.push(`+ ${c.path}${c.from ? `  (from ${c.from})` : ""}`); }
      } else if (c.op === "delete") {
        tree.push({ path: full, mode: "100644", type: "blob", sha: null });
        delete manifest.files[c.path];
        changes.push({ path: c.path, sha: null });
        counts.del++; lines.push(`- ${c.path}`);
      } else {
        tree.push({ path: `${IMAGES_DIR}/${c.to}`, mode: "100644", type: "blob", sha: c.sha });
        tree.push({ path: full, mode: "100644", type: "blob", sha: null });
        manifest.files[c.to] = Object.assign({}, manifest.files[c.path] || {}, { by: who.actor, at });
        delete manifest.files[c.path];
        changes.push({ path: c.path, sha: null }, { path: c.to, sha: c.sha });
        counts.mov++; lines.push(`> ${c.path} -> ${c.to}`);
      }
    }
    const sorted = Object.fromEntries(Object.keys(manifest.files).sort(byteOrder).map((k) => [k, manifest.files[k]]));
    tree.push({ path: `${IMAGES_DIR}/${IMAGE_MANIFEST}`, mode: "100644", type: "blob", content: JSON.stringify({ ...manifest, files: sorted }, null, 1) + "\n" });

    const words = [];
    if (counts.put) words.push(`add ${counts.put}`);
    if (counts.rep) words.push(`replace ${counts.rep}`);
    if (counts.mov) words.push(`rename ${counts.mov}`);
    if (counts.del) words.push(`delete ${counts.del}`);
    const message = `Scuffed images: ${words.join(", ")}\n\n${lines.join("\n")}\n\nSaved by ${who.actor} from kanaris-beans.com/scuffed_dev/images/`;
    try {
      const commit = await gh.commit(head, tree, message);
      return { commit, changes, live: await liveFiles(tree) };
    } catch (err) {
      if (err.github === 422 && attempt < SAVE_RETRIES) { await backoff(attempt); continue; }
      throw err;
    }
  }
}

// ---------- deploys: is a commit live on kanaris-beans.com yet? ----------
//
// GET  /deploy?sha=<commit>  -> { run: { status, conclusion, url, created } | null, latest: { sha, status,
//                               conclusion, created } | null }   the "pages build and deployment" run for that
//                               commit, and the newest one (GitHub skips a build when a newer commit came first)
// POST /redeploy  <- { sha }  -> { commit }   an empty commit on main, so GitHub Pages builds the site again

const PAGES_RUN = "pages build and deployment";

async function githubDeployData(gh, path, etag) {
  const url = gh.fresh(gh.base + path);
  const signal = AbortSignal.timeout(5000);
  const publicHeaders = { Accept: gh.headers.Accept, "User-Agent": "scuffed-perms", "Cache-Control": "no-cache" };
  const headers = { ...gh.headers, "Cache-Control": "no-cache" };
  if (etag) headers["If-None-Match"] = etag;
  let res = await fetch(url, { headers, signal });
  if (gh.headers.Authorization && (res.status === 403 || res.status === 404) &&
      res.headers.get("X-RateLimit-Remaining") !== "0" && !res.headers.has("Retry-After")) {
    res = await fetch(url, { headers: publicHeaders, signal });
  }
  return res;
}

async function actionsData(gh, path) {
  const res = await githubDeployData(gh, path);
  if (!res.ok) throw new HttpError(502, `Couldn't read the GitHub Pages builds (${res.status}).`);
  return res.json();
}

function pagesRuns(data) {
  return (data.workflow_runs || []).filter((r) => r.name === PAGES_RUN)
    .map((r) => ({ id: r.id, sha: r.head_sha, status: r.status, conclusion: r.conclusion, url: r.html_url, created: r.created_at, message: (r.head_commit && r.head_commit.message) || "" }));
}

async function actionsRuns(gh, query) {
  return pagesRuns(await actionsData(gh, `/actions/runs?${query}`));
}

// What main holds now for some paths: { path: sha | null }. One directory listing per folder, so a watch on an
// image + the manifest costs two requests. Lets the watcher tell "replaced by a newer commit" from "not live yet".
async function currentShas(gh, paths) {
  const head = await gh.head();
  const dirs = {};
  paths.forEach((p) => { const d = p.split("/").slice(0, -1).join("/"); (dirs[d] = dirs[d] || []).push(p); });
  const out = {};
  await Promise.all(Object.keys(dirs).slice(0, 10).map(async (d) => {
    let list = [];
    try { list = await gh.call(`/contents/${d.split("/").map(encodeURIComponent).join("/")}?ref=${head}`); } catch (e) { if (e.github !== 404) throw e; }
    const byName = Object.fromEntries((Array.isArray(list) ? list : []).map((it) => [it.path, it.sha]));
    dirs[d].forEach((p) => { out[p] = byName[p] || null; });
  }));
  return { head, shas: out };
}

function recentPagesRuns(gh) {
  return actionsRuns(gh, `branch=${encodeURIComponent(gh.branch)}&event=dynamic&per_page=20`);
}

function pagesJobs({ jobs = [] }) {
  return jobs.filter((job) => job.name === "build" || job.name === "deploy").map((job) => ({
    name: job.name,
    status: job.status,
    conclusion: job.conclusion,
    step: (job.steps || []).find((step) => step.status === "in_progress")?.name || null,
  }));
}

async function handleDeployStatus(request, env, ctx) {
  const cache = globalThis.caches?.default;
  const key = new Request(new URL("/__scuffed-pages-status-v2", request.url));
  const saved = await cache?.match(key).then((res) => res?.json()).catch(() => null);
  if (saved?.expires > Date.now()) {
    if (saved.error) throw new HttpError(502, saved.error);
    return saved.result;
  }

  const gh = new GitHub(env);
  const sources = {};
  function store(snapshot) {
    if (!cache) return;
    const response = Response.json(snapshot, { headers: { "Cache-Control": "public, max-age=3600" } });
    ctx.waitUntil(cache.put(key, response).catch(() => {}));
  }
  async function read(path, select) {
    const previous = saved?.sources[path];
    const res = await githubDeployData(gh, path, previous?.etag);
    if (res.status === 304 && previous) {
      sources[path] = previous;
    } else if (res.ok) {
      sources[path] = { etag: res.headers.get("ETag"), data: select(await res.json()) };
    } else {
      const err = new HttpError(502, `Couldn't read the GitHub Pages builds (${res.status}).`);
      if (res.status === 403 || res.status === 429) {
        const reset = res.headers.get("X-RateLimit-Remaining") === "0" ? Number(res.headers.get("X-RateLimit-Reset")) * 1000 : 0;
        err.retryAt = Math.max(Date.now() + (Number(res.headers.get("Retry-After")) || 60) * 1000, reset);
      }
      throw err;
    }
    return sources[path].data;
  }

  try {
    const [runs, head, live] = await Promise.all([
      read(`/actions/runs?branch=${encodeURIComponent(gh.branch)}&event=dynamic&per_page=50`, pagesRuns),
      read(`/git/ref/heads/${gh.branch}`, (data) => data.object.sha),
      livePagesRevision(),
    ]);
    const active = runs.filter((run) => run.status !== "completed");
    const jobs = new Map();
    // A job listing can lag the run. Limit concurrent requests and keep the workflow-level status if it does.
    for (let i = 0; i < active.length; i += 4) {
      await Promise.all(active.slice(i, i + 4).map(async (run) => {
        const path = `/actions/runs/${run.id}/jobs?filter=latest&per_page=20`;
        try {
          jobs.set(run.id, await read(path, pagesJobs));
        } catch (err) {
          if (err.retryAt) throw err;
        }
      }));
    }
    const result = { runs: runs.map((run) => jobs.has(run.id) ? { ...run, jobs: jobs.get(run.id) } : run), head, live };
    store({ result, sources, expires: Date.now() + 3000 });
    return result;
  } catch (err) {
    store({ error: err.message, sources: { ...saved?.sources, ...sources }, expires: err.retryAt || Date.now() + 3000 });
    throw err;
  }
}

async function handleDeploy(request, env) {
  const q = new URL(request.url).searchParams;
  const sha = String(q.get("sha") || "");
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new HttpError(400, "Give the full commit sha.");
  const paths = String(q.get("paths") || "").split(",").map((s) => s.trim()).filter(Boolean).slice(0, 40);
  const gh = new GitHub(env);
  const [mine, recent, cur, live] = await Promise.all([
    actionsRuns(gh, `head_sha=${sha}&per_page=5`),
    recentPagesRuns(gh),
    paths.length && env.GITHUB_TOKEN ? currentShas(gh, paths) : Promise.resolve(null),
    livePagesRevision(),
  ]);
  return { run: mine[0] || null, latest: recent[0] || null, head: cur && cur.head, current: cur ? cur.shas : null, live };
}

async function handleRedeploy(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "The perms server still needs its GitHub token.");
  let body = {};
  try { body = await request.json(); } catch { /* sha is optional */ }
  const was = /^[0-9a-f]{40}$/.test(String(body.sha || "")) ? String(body.sha) : "";
  const gh = new GitHub(env);
  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const parent = await gh.call(`/git/commits/${head}`);
    // same files as now, new commit: GitHub Pages sees a push and builds again
    const commit = await gh.call("/git/commits", "POST", {
      message: `Redeploy kanaris-beans.com${was ? ` (for ${was.slice(0, 7)})` : ""}\n\nRequested by ${who.actor} from scuffed_dev`,
      tree: parent.tree.sha, parents: [head],
    });
    try {
      await gh.call(`/git/refs/heads/${gh.branch}`, "PATCH", { sha: commit.sha, force: false });
      return { commit: commit.sha };
    } catch (err) {
      if (err.github === 422 && attempt < SAVE_RETRIES) { await backoff(attempt); continue; }
      throw err;
    }
  }
}

// The announcement notification: the title says whose board it is. The file is the board text plus
// "[notifier] @<time> text" lines (lobby pop-ups). The app keeps each pop-up's @time when you save again and stamps
// new ones with the save time, so a pop-up line that wasn't in the file before (`before`) was just sent: when there
// is one, the notification shows exactly that message. With no new pop-up (only the board text changed) it shows
// the board text. The app's history keeps the same body, in full if the push service had to trim it.
function announceNotice(world, text, before) {
  const name = WORLDS[world] || world;
  const NOTE = /^\s*\[notifier\]\s*(?:@\S+\s+)?(.*)$/i;
  const lines = (t) => String(t || "").replace(/\r/g, "").split("\n");
  const old = new Set(lines(before).filter((l) => NOTE.test(l)).map((l) => l.trim()));
  const board = [], fresh = [];
  lines(text).forEach((line) => {
    const m = NOTE.exec(line);
    if (!m) board.push(line);
    else if (m[1].trim() && !old.has(line.trim())) fresh.push(m[1].trim());
  });
  const body = fresh.length ? fresh.join("\n") : board.join("\n").trim();
  return { kind: "announce", title: `📣 ${name} announcement`, body: body || "(the announcements were cleared)",
    url: `/scuffed_dev/app/#announce/${world}`, tag: `announce-${world}` };
}

export default {
  async scheduled(event, env, ctx) {
    // once a minute: new world builds, new dev board activity, finished GitHub Pages builds -> notifications
    ctx.waitUntil(runSchedule(env, () => recentPagesRuns(new GitHub(env))).then((r) => {
      if (r && (r.boardError || r.deployError || r.worldError)) console.error("push schedule:", JSON.stringify(r));
    }));
  },

  async fetch(request, env, ctx) {
    const cors = corsHeaders(request, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    const { pathname } = new URL(request.url);

    try {
      if (request.method === "GET" && pathname === "/health") return json({ ok: true }, 200, cors);

      // push notifications for the scuffed_dev app (push.js)
      if (request.method === "GET" && pathname === "/push/key") {
        return json({ key: env.VAPID_PUBLIC || null, ready: pushReady(env) }, 200, cors);
      }
      if (request.method === "POST" && pathname === "/push/test") {
        const who = await staffOf(request, env, MODERATOR_LEVEL);
        let body = {};
        try { body = await request.json(); } catch { /* checked below */ }
        if (!/^https:\/\//.test(String(body.endpoint || ""))) throw new HttpError(400, "Turn notifications on in the app first.");
        if (!pushReady(env)) throw new HttpError(503, "Notifications aren't switched on yet on the server.");
        const r = await notify(env, { kind: "test", title: "🔔 scuffed_dev", body: `Notifications work, ${who.actor}. This is what they'll look like.`, url: "/scuffed_dev/app/#settings", tag: "test" }, String(body.endpoint));
        return json(r, 200, cors);
      }

      // Read-only status from this site's public Pages builds. File checks and retries still require staff.
      if (request.method === "GET" && pathname === "/deploy/status") {
        return json(await handleDeployStatus(request, env, ctx), 200, cors);
      }
      if (request.method === "GET" && pathname === "/deploy") {
        await staffOf(request, env, MODERATOR_LEVEL);
        return json(await handleDeploy(request, env), 200, cors);
      }
      if (request.method === "POST" && pathname === "/redeploy") {
        const who = await staffOf(request, env, MODERATOR_LEVEL);
        return json(await handleRedeploy(request, env, who), 200, cors);
      }

      if (request.method === "GET" && pathname === "/lists") {
        const who = await staffOf(request, env);
        return json({ ...(await handleLists(env)), you: who }, 200, cors);
      }
      if (request.method === "POST" && pathname === "/save") {
        const who = await staffOf(request, env);
        return json(await handleSave(request, env, who), 200, cors);
      }
      if (request.method === "GET" && pathname === "/announcements") {
        await staffOf(request, env, MODERATOR_LEVEL);
        return json(await handleAnnouncementGet(request, env), 200, cors);
      }
      if (request.method === "POST" && pathname === "/announcements") {
        const who = await staffOf(request, env, MODERATOR_LEVEL);
        const { before, ...res } = await handleAnnouncementSave(request, env, who);
        if (res.commit && pushReady(env)) ctx.waitUntil(notify(env, announceNotice(res.world, res.text, before)).catch((e) => console.error("announce push:", e)));
        return json(res, 200, cors);
      }
      // App-only announcement (the app's Announcements > App only): a notification and an Inbox entry for everyone
      // on the scuffed_dev app who gets announcements (moderator and up, per-phone prefs as usual). Nothing in the
      // worlds changes and nothing is committed. Its url opens the Inbox, which is how the app tells these apart
      // from world announcements (those open #announce/<world>).
      if (request.method === "POST" && pathname === "/announcements/app") {
        const who = await staffOf(request, env, MODERATOR_LEVEL);
        let body;
        try { body = await request.json(); } catch { throw new HttpError(400, "Body must be JSON."); }
        const text = String((body && body.text) || "").replace(/\r/g, "").trim();
        const title = String((body && body.title) || "").replace(/[\r\n]+/g, " ").trim().slice(0, 120);
        if (!text) throw new HttpError(400, "Write the announcement first.");
        if (text.length > MAX_ANNOUNCEMENT) throw new HttpError(400, `Announcements can be at most ${MAX_ANNOUNCEMENT} characters.`);
        if (!pushReady(env)) throw new HttpError(503, "Notifications aren't switched on yet on the server.");
        const r = await notify(env, { kind: "announce", title: `📣 ${title || "scuffed_dev announcement"}`, body: `${text}\n\n— ${who.actor}`,
          url: "/scuffed_dev/app/#history", tag: `app-announce-${Date.now()}`, meta: { app: true, by: who.actor } });
        return json(r, 200, cors);
      }
      if (request.method === "GET" && pathname === "/images") {
        const who = await staffOf(request, env, IMAGE_LEVEL);
        return json({ ...(await handleImagesGet(env)), you: who }, 200, cors);
      }
      if (request.method === "GET" && pathname === "/images/log") {
        await staffOf(request, env, IMAGE_LEVEL);
        return json(await handleImagesLog(env), 200, cors);
      }
      if (request.method === "POST" && pathname === "/images") {
        const who = await staffOf(request, env, IMAGE_DEV_LEVEL);
        return json(await handleImagesSave(request, env, who), 200, cors);
      }
      if (request.method === "POST" && pathname === "/images/suggest") {
        const who = await staffOf(request, env, IMAGE_SUGGEST_LEVEL);
        const res = await handleImagesSuggest(request, env, who);
        if (pushReady(env) && res.suggestions && res.suggestions.length) {
          const paths = res.suggestions.map((s) => s.path);
          const note = res.suggestions[0].note;
          ctx.waitUntil(notify(env, {
            kind: "suggest", title: "💡 New image suggestion" + (paths.length > 1 ? `s (${paths.length})` : ""),
            body: `${who.actor} suggested ${paths.join(", ")}${note ? `\n\n“${note}”` : ""}`,
            url: "/scuffed_dev/app/#images/suggestions", tag: "suggest-images",
          }).catch((e) => console.error("suggest push:", e)));
        }
        return json(res, 200, cors);
      }
      if (request.method === "POST" && pathname === "/images/review") {
        const who = await staffOf(request, env, IMAGE_SUGGEST_LEVEL);
        return json(await handleImagesReview(request, env, who), 200, cors);
      }
      return json({ error: "Not found" }, 404, cors);
    } catch (err) {
      const status = err instanceof HttpError ? err.status : 500;
      if (status >= 500) console.error(`${request.method} ${pathname}:`, err);
      return json({ error: err.message || "Something went wrong", code: err.code || undefined }, status, cors);
    }
  },
};
