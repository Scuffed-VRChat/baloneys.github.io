// scuffed-perms Worker: the only thing that can change the Scuffed role lists from the site.
//
// The editor page (kanaris-beans.com/scuffed_perms/) signs in with the same Supabase player account as the
// games and chat. Every request carries that session (Authorization: Bearer <access token>) and, for the
// master login, the moderation session token (X-Mod-Token). Before anything else the Worker asks Supabase
// who that is (public.mod_me, the same check the moderation panel uses) and refuses anyone below ADMIN.
// Hiding the editor in the page is only convenience: this check is what keeps everyone else out.
//
// GET  /lists  -> { head, files: [{ name, sha, text }] }       (admins only)
// POST /save   <- { head, changes: { "<file>": { sha, names: [..] } } }
//              -> { commit, files }   one commit: the changed lists + a rebuilt all.txt
//
// Config: cloudflare.config.ts (Supabase URL + anon key are public). GITHUB_TOKEN is a secret added after
// deploying (npx wrangler secret put GITHUB_TOKEN --name scuffed-perms). Without it the lists can still be
// viewed (read from the public all.txt) but /save refuses.
//
// A list's "sha" here is a hash of its non-blank lines, not GitHub's blob id, so it means the same thing
// whether the lists came from the GitHub API or from all.txt.

const ADMIN_LEVEL = 3; // helper 1, moderator 2, admin 3, dev 4, master 5 (supabase/migrations/2026-10-10-chat-moderation.sql)
const BUNDLE = "all.txt";
const MAX_NAMES = 500;
const MAX_NAME_LENGTH = 64;

// ---------- small helpers ----------

function corsHeaders(request, env) {
  const origin = request.headers.get("Origin") || "";
  const allowed = String(env.ALLOWED_ORIGINS || "").split(",").map((s) => s.trim()).filter(Boolean);
  const headers = {
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Authorization, Content-Type, X-Mod-Token",
    "Access-Control-Max-Age": "86400",
    Vary: "Origin",
  };
  if (allowed.includes(origin)) headers["Access-Control-Allow-Origin"] = origin;
  return headers;
}

function json(data, status, cors) {
  return new Response(JSON.stringify(data), {
    status: status || 200,
    headers: { "Content-Type": "application/json", "Cache-Control": "no-store", ...cors },
  });
}

class HttpError extends Error {
  constructor(status, message) { super(message); this.status = status; }
}

function encodeBase64(str) {
  const bytes = new TextEncoder().encode(str);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(bin);
}

function decodeBase64(b64) {
  const bin = atob(String(b64).replace(/\s/g, ""));
  return new TextDecoder().decode(Uint8Array.from(bin, (c) => c.charCodeAt(0)));
}

function splitLines(text) {
  return String(text || "").replace(/\r/g, "").split("\n").filter((l) => !/^\s*$/.test(l));
}

const byteOrder = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Identifies a list's contents (blank lines and CRs ignored), for "did someone else change it?".
async function contentId(text) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(splitLines(text).join("\n")));
  return "h" + [...new Uint8Array(digest)].slice(0, 12).map((b) => b.toString(16).padStart(2, "0")).join("");
}

// The lists from the public all.txt: { name, text } per "### FILE:" section.
function parseBundle(text) {
  const files = [];
  let current = null;
  for (const line of String(text || "").replace(/\r/g, "").split("\n")) {
    if (line.startsWith("### FILE: ")) { current = { name: line.slice(10).trim(), lines: [] }; files.push(current); continue; }
    if (current && !/^\s*$/.test(line)) current.lines.push(line);
  }
  return files.map((f) => ({ name: f.name, text: f.lines.length ? f.lines.join("\n") + "\n" : "" }));
}

// Same output as .github/scripts/combine-scuffed-perms.sh (and the old page). Keep them in step.
function buildBundle(dir, fileLines) {
  const out = [
    "# AUTO-GENERATED - do not edit this file.",
    `# Built from the other files in ${dir}/ (kanaris-beans.com/scuffed_perms/ or .github/workflows/combine-scuffed-perms.yml).`,
    "# Edit the individual role files instead.",
  ];
  for (const name of Object.keys(fileLines).sort(byteOrder)) {
    out.push("", `### FILE: ${name}`, ...fileLines[name]);
  }
  return out.join("\n") + "\n";
}

// Why a name can't go on a list, or "" if it can. Mirrors the checks in the page.
function nameProblem(name) {
  if (!name) return "empty name";
  if (name.length > MAX_NAME_LENGTH) return `"${name.slice(0, 20)}…" is longer than ${MAX_NAME_LENGTH} characters`;
  if (/[\r\n]/.test(name)) return "names can't contain line breaks";
  if (name.includes(",")) return `"${name}" contains a comma (the world reads a comma as "next name")`;
  if (name.startsWith("#") || name.startsWith("//")) return `"${name}" starts with # or // (the world reads that as a comment)`;
  if (name.startsWith("### FILE:")) return `"${name}" is reserved`;
  return "";
}

// ---------- Supabase: who is asking? ----------

async function staffOf(request, env) {
  const auth = request.headers.get("Authorization") || "";
  const userJwt = auth.startsWith("Bearer ") ? auth.slice(7).trim() : "";
  const modToken = (request.headers.get("X-Mod-Token") || "").trim();
  if (!userJwt && !modToken) throw new HttpError(401, "Sign in first.");

  const res = await fetch(`${env.SUPABASE_URL}/rest/v1/rpc/mod_me`, {
    method: "POST",
    headers: {
      apikey: env.SUPABASE_ANON_KEY,
      Authorization: `Bearer ${userJwt || env.SUPABASE_ANON_KEY}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ token: modToken || null }),
  });
  if (res.status === 401) throw new HttpError(401, "Your sign-in has expired. Reload the page.");
  if (!res.ok) throw new HttpError(502, `Couldn't check your staff level (${res.status}).`);
  const me = await res.json();
  const level = Number(me && me.level) || 0;
  if (level < ADMIN_LEVEL) throw new HttpError(403, "Admins only.");
  return { level, actor: (me && me.actor) || "admin" };
}

// ---------- GitHub ----------

class GitHub {
  constructor(env) {
    this.base = `https://api.github.com/repos/${env.REPO_OWNER}/${env.REPO_NAME}`;
    this.branch = env.BRANCH || "main";
    this.dir = env.ROLES_DIR || "scuffed_perms/roles";
    this.raw = `https://raw.githubusercontent.com/${env.REPO_OWNER}/${env.REPO_NAME}/refs/heads/${this.branch}/`;
    this.headers = {
      Accept: "application/vnd.github+json",
      "User-Agent": "scuffed-perms",
      "X-GitHub-Api-Version": "2022-11-28",
    };
    if (env.GITHUB_TOKEN) this.headers.Authorization = `Bearer ${env.GITHUB_TOKEN}`;
  }

  // No token: read the lists from the public all.txt (can lag a few minutes behind a save: GitHub's CDN).
  async listsFromBundle() {
    const res = await fetch(this.raw + this.dir + "/" + BUNDLE, { headers: { "User-Agent": "scuffed-perms" } });
    if (!res.ok) throw new HttpError(502, `Couldn't read ${BUNDLE} (${res.status}).`);
    const files = parseBundle(await res.text());
    return Promise.all(files.map(async (f) => ({ ...f, sha: await contentId(f.text) })));
  }

  async call(path, method, body) {
    const res = await fetch(this.base + path, {
      method: method || "GET",
      headers: body ? { ...this.headers, "Content-Type": "application/json" } : this.headers,
      body: body ? JSON.stringify(body) : undefined,
    });
    const text = await res.text();
    let data = null;
    try { data = text ? JSON.parse(text) : null; } catch { data = text; }
    if (!res.ok) {
      const err = new HttpError(res.status === 409 || res.status === 422 ? 409 : 502,
        `GitHub ${method || "GET"} ${path} failed: ${res.status} ${(data && data.message) || ""}`.trim());
      err.github = res.status;
      throw err;
    }
    return data;
  }

  head() { return this.call(`/git/ref/heads/${this.branch}`).then((d) => d.object.sha); }

  // Every role list at a commit, all.txt left out.
  async lists(commit) {
    const items = await this.call(`/contents/${this.dir.split("/").map(encodeURIComponent).join("/")}?ref=${commit}`);
    const files = (items || []).filter((it) => it.type === "file" && it.name !== BUNDLE);
    return Promise.all(files.map(async (f) => {
      const blob = await this.call(`/git/blobs/${f.sha}`);
      const text = decodeBase64(blob.content);
      return { name: f.name, sha: await contentId(text), text };
    }));
  }

  async commit(head, tree, message) {
    const parent = await this.call(`/git/commits/${head}`);
    const newTree = await this.call("/git/trees", "POST", { base_tree: parent.tree.sha, tree });
    const commit = await this.call("/git/commits", "POST", { message, tree: newTree.sha, parents: [head] });
    await this.call(`/git/refs/heads/${this.branch}`, "PATCH", { sha: commit.sha, force: false });
    return commit.sha;
  }
}

// ---------- handlers ----------

async function handleLists(env) {
  const gh = new GitHub(env);
  if (!env.GITHUB_TOKEN) return { head: null, files: await gh.listsFromBundle(), canSave: false };
  const head = await gh.head();
  const files = await gh.lists(head);
  return { head, files, canSave: true };
}

async function handleSave(request, env, who) {
  if (!env.GITHUB_TOKEN) throw new HttpError(503, "Saving isn't switched on yet: the perms server still needs its GitHub token.");
  let body;
  try { body = await request.json(); } catch { throw new HttpError(400, "Body must be JSON."); }
  const changes = body && body.changes && typeof body.changes === "object" ? body.changes : null;
  if (!changes || !Object.keys(changes).length) throw new HttpError(400, "Nothing to save.");

  const gh = new GitHub(env);

  for (let attempt = 0; ; attempt++) {
    const head = await gh.head();
    const current = await gh.lists(head);
    const byName = Object.fromEntries(current.map((f) => [f.name, f]));

    // Only existing role files can be edited, and only from the version the editor loaded.
    const clashes = [];
    const fileLines = Object.fromEntries(current.map((f) => [f.name, splitLines(f.text)]));
    const tree = [];
    const summary = [];
    for (const [name, change] of Object.entries(changes)) {
      const file = byName[name];
      if (!file) throw new HttpError(400, `There's no role list called "${name}".`);
      if (!change || !Array.isArray(change.names)) throw new HttpError(400, `Bad change for "${name}".`);
      if (change.sha !== file.sha) { clashes.push(name); continue; }
      if (change.names.length > MAX_NAMES) throw new HttpError(400, `"${name}" can hold at most ${MAX_NAMES} names.`);

      // Comment lines in the file stay where they are; the names become exactly what the editor sent.
      const names = [];
      const seen = new Set();
      for (const raw of change.names) {
        const n = String(raw).trim();
        const problem = nameProblem(n);
        if (problem) throw new HttpError(400, `${name}: ${problem}.`);
        if (seen.has(n.toLowerCase())) continue;
        seen.add(n.toLowerCase());
        names.push(n);
      }
      const before = fileLines[name];
      const isComment = (l) => { const t = l.trim(); return t.startsWith("#") || t.startsWith("//"); };
      const lines = [...before.filter(isComment), ...names];
      const oldNames = before.filter((l) => !isComment(l)).map((l) => l.trim());
      const added = names.filter((n) => !oldNames.some((o) => o.toLowerCase() === n.toLowerCase()));
      const removed = oldNames.filter((o) => !names.some((n) => n.toLowerCase() === o.toLowerCase()));
      if (!added.length && !removed.length && lines.join("\n") === before.join("\n")) continue;
      fileLines[name] = lines;
      tree.push({ path: `${gh.dir}/${name}`, mode: "100644", type: "blob", content: lines.length ? lines.join("\n") + "\n" : "" });
      summary.push(`${name} ${[...added.map((n) => "+" + n), ...removed.map((n) => "-" + n)].join(" ")}`.trim());
    }
    if (clashes.length) {
      throw new HttpError(409, `Someone else changed ${clashes.join(", ")} after you opened the page. Reload and make your changes again.`);
    }
    if (!tree.length) return { commit: null, unchanged: true };

    tree.push({ path: `${gh.dir}/${BUNDLE}`, mode: "100644", type: "blob", content: buildBundle(gh.dir, fileLines) });
    let message = `Scuffed perms: ${summary.join("; ")}`;
    if (message.length > 300) message = message.slice(0, 297) + "...";
    message += `\n\nSaved by ${who.actor} from kanaris-beans.com/scuffed_perms/`;

    try {
      const commit = await gh.commit(head, tree, message);
      return { commit };
    } catch (err) {
      // The branch moved between our read and our write: start again from the new head once.
      if (err.github === 422 && attempt < 1) continue;
      throw err;
    }
  }
}

export default {
  async fetch(request, env) {
    const cors = corsHeaders(request, env);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
    const { pathname } = new URL(request.url);

    try {
      if (request.method === "GET" && pathname === "/health") return json({ ok: true }, 200, cors);

      if (request.method === "GET" && pathname === "/lists") {
        const who = await staffOf(request, env);
        return json({ ...(await handleLists(env)), you: who }, 200, cors);
      }
      if (request.method === "POST" && pathname === "/save") {
        const who = await staffOf(request, env);
        return json(await handleSave(request, env, who), 200, cors);
      }
      return json({ error: "Not found" }, 404, cors);
    } catch (err) {
      const status = err instanceof HttpError ? err.status : 500;
      if (status >= 500) console.error(`${request.method} ${pathname}:`, err);
      return json({ error: err.message || "Something went wrong" }, status, cors);
    }
  },
};
